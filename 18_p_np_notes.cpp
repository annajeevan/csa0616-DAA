#include <iostream>
using namespace std;

int main() {

    cout << "P:\n";
    cout << "Problems that can be solved in polynomial time.\n\n";

    cout << "NP:\n";
    cout << "Problems whose solutions can be verified in polynomial time.\n\n";

    cout << "NP-Hard:\n";
    cout << "Problems at least as hard as every problem in NP.\n\n";

    cout << "NP-Complete:\n";
    cout << "Problems that are both NP and NP-Hard.\n\n";

    cout << "Examples of NP-Complete problems:\n";
    cout << "1. SAT\n";
    cout << "2. 3-SAT\n";
    cout << "3. Vertex Cover\n";
    cout << "4. Hamiltonian Cycle\n";

    return 0;
}
